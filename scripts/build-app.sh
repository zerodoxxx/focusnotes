#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
ROOT_DIR="$(cd "$SCRIPT_DIR/.." && pwd -P)"

if [[ $# -gt 1 ]]; then
    printf 'Usage: %s [debug|release]\n' "$0" >&2
    exit 2
fi

CONFIGURATION="${1:-debug}"
case "$CONFIGURATION" in
    debug|release) ;;
    *)
        printf 'Invalid configuration: %s (expected debug or release)\n' "$CONFIGURATION" >&2
        exit 2
        ;;
esac

while IFS='=' read -r key value; do
    case "$key" in
        APPNAME) APPNAME="$value" ;;
        BUNDLE_PREFIX) BUNDLE_PREFIX="$value" ;;
        VERSION) VERSION="$value" ;;
        BUILD) BUILD="$value" ;;
        MIN_MACOS) MIN_MACOS="$value" ;;
        GITHUB_REPO) GITHUB_REPO="$value" ;;
        SPARKLE_PUBLIC_ED_KEY) SPARKLE_PUBLIC_ED_KEY="$value" ;;
    esac
done < "$ROOT_DIR/Config/app.env"

APPNAME_LOWER="$(printf '%s' "$APPNAME" | LC_ALL=C tr '[:upper:]' '[:lower:]' | LC_ALL=C sed 's/[^a-z0-9-]/-/g')"
BUNDLE_ID="$BUNDLE_PREFIX.$APPNAME_LOWER"
BUNDLE_PATH="$ROOT_DIR/build/$APPNAME.app"
CONTENTS_PATH="$BUNDLE_PATH/Contents"
PLIST_PATH="$CONTENTS_PATH/Info.plist"
APP_EXE="$CONTENTS_PATH/MacOS/$APPNAME"
HELPER_EXE="$CONTENTS_PATH/MacOS/EmbedHelper"
SPARKLE_FW="$CONTENTS_PATH/Frameworks/Sparkle.framework"

# Validate the configured basename and both existing parent/target paths before
# SwiftPM or the bundle cleanup can write outside the checkout.
python3 "$SCRIPT_DIR/check-app-path.py" "$APPNAME" "$ROOT_DIR/build"
python3 "$SCRIPT_DIR/check-app-path.py" "$APPNAME" "$ROOT_DIR" .build

swift build -c "$CONFIGURATION"
BIN_DIR="$(swift build -c "$CONFIGURATION" --show-bin-path)"

python3 "$SCRIPT_DIR/check-app-path.py" "$APPNAME" "$ROOT_DIR/build"
python3 "$SCRIPT_DIR/check-app-path.py" "$APPNAME" "$ROOT_DIR" .build

python3 - "$BUNDLE_PATH" <<'PY'
from pathlib import Path
import shutil
import sys

bundle = Path(sys.argv[1])
if bundle.is_symlink() or bundle.is_file():
    bundle.unlink()
elif bundle.exists():
    shutil.rmtree(bundle)
PY

mkdir -p "$CONTENTS_PATH/MacOS"
cp "$BIN_DIR/App" "$APP_EXE"
chmod 755 "$APP_EXE"
cp "$BIN_DIR/EmbedHelper" "$HELPER_EXE"
chmod 755 "$HELPER_EXE"

# Sparkle is a binary artifact that SwiftPM unpacks under .build/artifacts.
SPARKLE_MATCHES=()
while IFS= read -r match; do
    SPARKLE_MATCHES+=("$match")
done < <(find "$ROOT_DIR/.build/artifacts" -type d -name Sparkle.framework -path "*macos*")
if [[ ${#SPARKLE_MATCHES[@]} -ne 1 ]]; then
    printf 'expected exactly one Sparkle.framework under %s/.build/artifacts, found %d (is the Sparkle package resolved?)\n' "$ROOT_DIR" "${#SPARKLE_MATCHES[@]}" >&2
    if [[ ${#SPARKLE_MATCHES[@]} -gt 0 ]]; then
        printf '  %s\n' "${SPARKLE_MATCHES[@]}" >&2
    fi
    exit 1
fi
SPARKLE_SRC="${SPARKLE_MATCHES[0]}"
mkdir -p "$CONTENTS_PATH/Frameworks"
ditto "$SPARKLE_SRC" "$SPARKLE_FW"

# SwiftPM bakes build-machine paths into LC_RPATH. Drop the ones that point into
# .build or the developer's home (paths may contain spaces, so keep the whole
# remainder of the "path" line), then make sure the app can find the embedded framework.
APP_RPATHS="$(otool -l "$APP_EXE" | awk '/LC_RPATH/{getline;getline;sub(/^ *path /,"");sub(/ \(offset [0-9]+\)$/,"");print}')"
while IFS= read -r rpath; do
    [[ -z "$rpath" ]] && continue
    case "$rpath" in
        */.build/*|/Users/*)
            install_name_tool -delete_rpath "$rpath" "$APP_EXE"
            ;;
    esac
done <<< "$APP_RPATHS"

if ! grep -Fxq '@executable_path/../Frameworks' <<< "$(otool -l "$APP_EXE" | awk '/LC_RPATH/{getline;getline;sub(/^ *path /,"");sub(/ \(offset [0-9]+\)$/,"");print}')"; then
    install_name_tool -add_rpath '@executable_path/../Frameworks' "$APP_EXE"
fi

APP_DEPS="$(otool -L "$APP_EXE")"
if ! grep -Fq '@rpath/Sparkle.framework/Versions/B/Sparkle' <<< "$APP_DEPS"; then
    printf 'error: %s does not reference @rpath/Sparkle.framework/Versions/B/Sparkle\n' "$APP_EXE" >&2
    exit 1
fi
while IFS= read -r rpath; do
    printf 'rpath: %s\n' "$rpath" >&2
done <<< "$(otool -l "$APP_EXE" | awk '/LC_RPATH/{getline;getline;sub(/^ *path /,"");sub(/ \(offset [0-9]+\)$/,"");print}')"

HELPER_DEPS="$(otool -L "$HELPER_EXE")"
if grep -qi 'sparkle' <<< "$HELPER_DEPS"; then
    printf 'error: %s must not link Sparkle\n' "$HELPER_EXE" >&2
    exit 1
fi

# Icons are generated by scripts/make-icons.swift.
mkdir -p "$CONTENTS_PATH/Resources"
cp "$ROOT_DIR/assets/icons/AppIcon.icns" "$CONTENTS_PATH/Resources/AppIcon.icns"
cp "$ROOT_DIR/assets/icons/MenuBarIcon.pdf" "$ROOT_DIR/assets/icons/MenuBarIcon-active.pdf" "$CONTENTS_PATH/Resources/"

# License texts for the bundled model, runtime and project.
cp "$ROOT_DIR/licenses/Apache-2.0.txt" "$CONTENTS_PATH/Resources/Apache-2.0.txt"
cp "$ROOT_DIR/licenses/EmbeddingGemma2-NOTICE.txt" "$CONTENTS_PATH/Resources/EmbeddingGemma2-NOTICE.txt"
cp "$ROOT_DIR/LICENSE" "$CONTENTS_PATH/Resources/LICENSE"
cp "$ROOT_DIR/THIRD_PARTY_NOTICES.md" "$CONTENTS_PATH/Resources/THIRD_PARTY_NOTICES.md"

plutil -create xml1 "$PLIST_PATH"
plutil -insert CFBundleName -string "$APPNAME" "$PLIST_PATH"
plutil -insert CFBundleDisplayName -string "$APPNAME" "$PLIST_PATH"
plutil -insert CFBundleExecutable -string "$APPNAME" "$PLIST_PATH"
plutil -insert CFBundleIconFile -string AppIcon "$PLIST_PATH"
plutil -insert CFBundleIdentifier -string "$BUNDLE_ID" "$PLIST_PATH"
plutil -insert CFBundleShortVersionString -string "$VERSION" "$PLIST_PATH"
plutil -insert CFBundleVersion -string "$BUILD" "$PLIST_PATH"
plutil -insert LSMinimumSystemVersion -string "$MIN_MACOS" "$PLIST_PATH"
plutil -insert LSUIElement -bool true "$PLIST_PATH"
plutil -insert NSHighResolutionCapable -bool true "$PLIST_PATH"
plutil -insert CFBundlePackageType -string APPL "$PLIST_PATH"
plutil -insert NSHumanReadableCopyright -string "Copyright © 2026 $APPNAME contributors. MIT License." "$PLIST_PATH"

# Sparkle updates need both the feed URL and the EdDSA public key. Without both,
# neither key is written and the app hides "Check for Updates…".
if [[ -n "${GITHUB_REPO:-}" && -n "${SPARKLE_PUBLIC_ED_KEY:-}" ]]; then
    plutil -insert SUFeedURL -string "https://github.com/$GITHUB_REPO/releases/latest/download/appcast.xml" "$PLIST_PATH"
    plutil -insert SUPublicEDKey -string "$SPARKLE_PUBLIC_ED_KEY" "$PLIST_PATH"
fi

# Signing. SIGN_ADHOC=1 forces an ad-hoc signature. Otherwise an explicit
# SIGN_IDENTITY is used as-is (with SIGN_KEYCHAIN if given); with neither set, the
# dedicated release keychain is used when it exists. Anything else is ad-hoc.
DEFAULT_SIGN_KEYCHAIN="$HOME/Library/Keychains/$APPNAME-signing.keychain-db"
if [[ "${SIGN_ADHOC:-0}" == 1 ]]; then
    SIGN_IDENTITY=""
elif [[ -z "${SIGN_IDENTITY:-}" && -f "$DEFAULT_SIGN_KEYCHAIN" ]]; then
    SIGN_IDENTITY="$APPNAME Release Signing"
    SIGN_KEYCHAIN="$DEFAULT_SIGN_KEYCHAIN"
fi

# One ordered list for both branches: nested Sparkle code deepest first, then the
# framework, then the helper, then the app bundle.
SIGN_PATHS=(
    "$SPARKLE_FW/Versions/B/XPCServices/Installer.xpc"
    "$SPARKLE_FW/Versions/B/XPCServices/Downloader.xpc"
    "$SPARKLE_FW/Versions/B/Autoupdate"
    "$SPARKLE_FW/Versions/B/Updater.app"
    "$SPARKLE_FW"
    "$HELPER_EXE"
    "$BUNDLE_PATH"
)

if [[ -n "${SIGN_IDENTITY:-}" && -n "${SIGN_KEYCHAIN:-}" && -n "${SIGNING_KEYCHAIN_PASSWORD:-}" ]]; then
    security unlock-keychain -p "$SIGNING_KEYCHAIN_PASSWORD" "$SIGN_KEYCHAIN" \
        || { printf 'could not unlock %s\n' "$SIGN_KEYCHAIN" >&2; exit 1; }
fi

sign_path() {
    if [[ -z "${SIGN_IDENTITY:-}" ]]; then
        codesign --force --sign - --timestamp=none "$1"
    elif [[ -n "${SIGN_KEYCHAIN:-}" ]]; then
        codesign --force --sign "$SIGN_IDENTITY" --keychain "$SIGN_KEYCHAIN" --timestamp=none "$1"
    else
        codesign --force --sign "$SIGN_IDENTITY" --timestamp=none "$1"
    fi
}

for signed_path in "${SIGN_PATHS[@]}"; do
    sign_path "$signed_path"
done

if [[ -n "${SIGN_IDENTITY:-}" ]]; then
    printf 'signed with identity: %s\n' "$SIGN_IDENTITY" >&2
else
    printf 'signed ad-hoc\n' >&2
fi

printf '%s\n' "$BUNDLE_PATH"
